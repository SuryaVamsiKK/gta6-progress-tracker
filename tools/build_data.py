"""Regenerate site/data.js from GTA6_Progress_Tracker.xlsx.

Usage (from the project root):  py -m pip install openpyxl   (once)
                                 py tools/build_data.py
"""
import json
import pathlib
import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent
wb = openpyxl.load_workbook(ROOT / "GTA6_Progress_Tracker.xlsx")


def rows(name):
    ws = wb[name]
    allr = list(ws.iter_rows(values_only=True))
    return allr[0][0], allr[1][0], allr[4:]


def num(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


out = {}

# Dashboard weights
dash = wb["Dashboard"]
out["weights"] = {
    dash.cell(r, 1).value: dash.cell(r, 5).value for r in range(5, 8)
}
out["weightNote"] = dash.cell(21, 1).value

# 100% checklist
t, s, rs = rows("100% Checklist")
items, notes = [], []
for r in rs:
    if isinstance(r[0], int):
        items.append({
            "id": r[0], "cat": r[1], "name": r[2], "req": num(r[3]),
            "total": r[4] if isinstance(r[4], (int, float)) else None,
            "done": num(r[5]), "note": r[9] if len(r) > 9 else None,
            "auto": "Challenges" if "Challenges tab" in str(r[9] or "") else None,
        })
    elif r[2]:
        notes.append(r[2])
out["checklist"] = {"title": t, "subtitle": s, "items": items, "notes": notes}

# Collectibles
t, s, rs = rows("Collectibles")
items, notes = [], []
for i, r in enumerate(rs):
    if r[0] and r[0] != "TOTAL" and r[1]:
        items.append({"id": f"{r[0]}|{r[1]}", "cat": r[0], "name": r[1], "total": num(r[2]), "done": num(r[3])})
    elif r[0] and r[0] != "TOTAL":
        notes.append(r[0])
out["collectibles"] = {"title": t, "subtitle": s, "items": items, "notes": notes}

# Challenges
t, s, rs = rows("Challenges")
items, notes = [], []
for r in rs:
    if r[0] and r[0] != "TOTAL" and r[1]:
        items.append({"id": r[0], "unlock5": r[1], "unlock10": r[2], "done": num(r[3])})
    elif r[0] and r[0] != "TOTAL":
        notes.append(r[0])
out["challenges"] = {"title": t, "subtitle": s, "items": items, "notes": notes}

# Story missions
t, s, rs = rows("Story Missions")
items = []
for r in rs:
    if isinstance(r[0], int):
        items.append({"id": r[0], "chapter": r[1], "name": r[2], "type": r[3],
                      "char": r[4], "status": r[5] or "Not started", "note": r[6]})
out["missions"] = {"title": t, "subtitle": s, "items": items}

# Trophies
t, s, rs = rows("Trophies")
tiers, known, notes, mode = [], [], [], "tiers"
for r in rs:
    if r[0] == "TOTAL":
        continue
    if r[0] == "Known trophy":
        mode = "known"
        continue
    if mode == "tiers" and r[0] and isinstance(r[1], int):
        tiers.append({"id": r[0], "total": r[1], "done": num(r[2])})
    elif mode == "known" and r[0] and r[1]:
        known.append({"id": r[0], "how": r[1], "done": r[2] == "Yes"})
    elif r[0]:
        notes.append(r[0])
out["trophies"] = {"title": t, "subtitle": s, "tiers": tiers, "known": known, "notes": notes}

# Regions
t, s, rs = rows("Regions")
items = []
for r in rs:
    if r[0] and r[1]:
        items.append({"id": r[0], "inspo": r[1], "desc": r[2], "pct": num(r[3]), "note": r[4]})
out["regions"] = {"title": t, "subtitle": s, "items": items}

# Sources
t, s, rs = rows("Sources & Notes")
src, caveats = [], []
for r in rs:
    if r[0] and r[2]:
        src.append({"name": r[0], "used": r[1], "url": r[2]})
    elif r[0] and r[0].startswith("•"):
        caveats.append(r[0].lstrip("• ").strip())
out["sources"] = {"title": t, "subtitle": s, "items": src, "caveats": caveats}

# Extras: character locks + full trophy list (tools/extra_data.json)
extra = json.loads((ROOT / "tools" / "extra_data.json").read_text(encoding="utf-8"))
locks = {int(k): v for k, v in extra["characterLocks"].items() if not k.startswith("_")}
for m in out["missions"]["items"]:
    if m["id"] in locks:
        m["lock"] = locks[m["id"]]
        m["char"] = m["char"] or locks[m["id"]]
known = {k["id"]: k["done"] for k in out["trophies"]["known"]}
for i, t in enumerate(extra["trophies"]):
    t["id"] = f"t{i}"
    t["done"] = known.get(t["name"], False)
out["trophies"]["list"] = extra["trophies"]
tier_totals = {t["id"]: t["total"] for t in out["trophies"]["tiers"]}
for tier, total in tier_totals.items():
    got = sum(1 for t in extra["trophies"] if t["tier"] == tier)
    if got != total:
        print(f"WARNING: {tier}: sheet says {total}, trophy list has {got}")

dest = ROOT / "site" / "data.js"
dest.write_text("// Generated by tools/build_data.py from GTA6_Progress_Tracker.xlsx. Do not edit by hand.\n"
                "window.GTA_DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(f"Wrote {dest} ({len(out['checklist']['items'])} checklist lines, "
      f"{len(out['missions']['items'])} missions, {len(out['collectibles']['items'])} collectibles)")
